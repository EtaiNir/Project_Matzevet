-- ═══════════════════════════════════════════════════════════════
-- 035 הגדירה "תלמיד של הרכז" = התחיל אחד מהמקצועות שלו, **ובמקצוע חובה
-- גם מי שעוד לא התחיל אף רמה**. בפועל רכז אנגלית 3+4+5 באגיאל ראה את כל 216
-- התלמידים, כי כולם לומדים אנגלית.
--
-- אייל, 13.10: *"בדפים של כל התלמידים ושאר הדפים הוא יראה רק תלמידים
-- שקיימים בדפים המקוריים שנבחרו לו"* — כלומר בדיוק מי שמופיע בדף המקצוע: מי
-- שיש לו ציון בשאלון אחד לפחות באחד המקצועות שלו. באגיאל: 185 (114 + 47 + 24,
-- אף תלמיד אינו בשתי רמות).
--
-- הכלל של "חובה — גם מי שלא התחיל" יוצא. המחיר ידוע ומקובל: תלמיד שעוד לא
-- ניגש לאף שאלון במקצוע (באגיאל — 31 תלמידי יב באנגלית) אינו מופיע אצל רכז
-- המקצוע. רכז הבגרויות ורכז השכבה ממשיכים לראות אותו.
--
-- אותה חתימה — bagrut_student_visible (035) לא משתנה.

create or replace function public.bagrut_subject_member(p_round uuid, p_student text, p_keys text[])
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  -- כמו דף המקצוע (BagrutSubject): תלמיד עם ציון שאלון אחד לפחות במקצוע
  select exists (
    select 1 from public.bagrut_grades g
     where g.round_id = p_round
       and g.student_id = p_student
       and g.subject_key = any(p_keys));
$$;

-- כבר לא בשימוש (היה לזיהוי רמות של מקצוע חובה ב-035)
drop function if exists public.bagrut_subject_family(text);
