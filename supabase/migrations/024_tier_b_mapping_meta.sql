-- מיגרציה 024: הערכת הביטחון של כל הצעת מיפוי בקליטת דרג ב'
--
-- ה-AI ממפה עכשיו בשתי שכבות: קודם לשדות המוכרים, ורק את מה שנשאר —
-- לרשימה מורחבת. לכל הצעה הוא מחזיר גם רמת ביטחון. מסך האישור משתמש
-- בזה כדי לסמן בצהוב את מה שכדאי לבדוק, ובירוק את מה שוודאי — כך
-- תשומת הלב הולכת לשורות שצריכות אותה, ולא מתפזרת על עשרים שורות זהות.
--
-- עמודה נפרדת ולא שדה בתוך proposed_mapping: המבנה של proposed_mapping
-- (כותרת → שדה) הוא מה שמסך האישור שולח חזרה כ-approved_mapping.
-- ערבוב המטא-דאטה לתוכו היה שובר את החוזה הזה.
--
-- מבנה: { "<כותרת>": { "tier": "core" | "extended",
--                      "confidence": "high" | "low" } }
-- ריק (null) למיפוי שמור או ידני — שם אין הערכה, יש החלטה של אדם.

alter table public.tier_b_uploads
  add column if not exists mapping_meta jsonb;

comment on column public.tier_b_uploads.mapping_meta is
  'לכל כותרת: באיזו שכבה נמצא השדה (core/extended) ורמת הביטחון של ה-AI (high/low).';
