-- בפגישת 5.10 התברר שמשקלים שמסתכמים ל-150% אינם טעות: חלק מהמקצוע אפשר
-- להשלים בשאלון זה *או* בזה (למשל עברית לערבים — 14331 או 14383, כל אחד
-- 30%). התוכנית עצמה תמיד 100%. עד עכשיו המסך והקליטה התריעו על זה —
-- התראת שווא, בדיוק הסוג ששורף את הכפתור האדום.
--
-- שאלונים שקולים באותו מקצוע חולקים מספר ב-alt_group, ובסכום המשקלים
-- נספר אחד מהם. load_bagrut.py מסמן אותם בקליטה: קבוצת שאלונים בעלי אותו
-- משקל, שספירתה פעם אחת משלימה את המקצוע ל-100% בדיוק. כל השאר — ריק.
--
-- עמודה ריקה בסבבים שנקלטו לפני המיגרציה — הם יסומנו בקליטה הבאה.

alter table public.bagrut_program
  add column if not exists alt_group smallint;

comment on column public.bagrut_program.alt_group is
  'שאלונים שקולים ("או/או") באותו מקצוע חולקים מספר; נספר אחד מהם בסכום המשקלים. null = שאלון רגיל';
